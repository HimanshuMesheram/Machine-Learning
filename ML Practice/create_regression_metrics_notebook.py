    "\n",
    "### Interpretation\n",
    "- **Range**: [0, ∞)\n",
    "- **Lower is better**\n",
    "- Unit: Same as the target variable\n",
    "- **Pros**: Easy to interpret, robust to outliers\n",
    "- **Cons**: Not differentiable at zero, doesn't penalize large errors heavily"
