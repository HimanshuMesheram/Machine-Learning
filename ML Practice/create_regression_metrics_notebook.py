    "# Function to calculate Adjusted R²\n",
    "def adjusted_r2_score(y_true, y_pred, n, p):\n",
    "    \"\"\"\n",
    "    Calculate adjusted R² score\n",
    "    \n",
    "    Parameters:\n",
    "    y_true: array-like, actual values\n",
    "    y_pred: array-like, predicted values  \n",
    "    n: int, number of samples\n",
    "    p: int, number of features\n",
    "    \"\"\"\n",
    "    r2 = r2_score(y_true, y_pred)\n",
    "    adjusted_r2 = 1 - (1 - r2) * (n - 1) / (n - p - 1)\n",
    "    return adjusted_r2\n",
    "\n",
    "# Example with different numbers of features\n",
    "np.random.seed(42)\n",
    "n_samples = 100\n",
    "n_features_list = [1, 5, 10, 20, 50]\n",
    "\n",
    "# Generate data with increasing features\n",
    "results = []\n",
    "\n",
    "for p in n_features_list:\n",
    "    # Generate X with p features\n",
    "    X = np.random.randn(n_samples, p)\n",
    "    # Generate y (only first 5 features are actually relevant)\n",
    "    true_coef = np.zeros(p)\n",
    "    base_coef = np.array([2, 1, 0.5, 0.3, 0.1])\n",
    "    true_coef[:min(p, len(base_coef))] = base_coef[:p]\n",
    "    y = X @ true_coef + np.random.normal(0, 0.1, n_samples)\n",
    "    \n",
    "    # Fit linear regression\n",
    "    model = LinearRegression()\n",
    "    model.fit(X, y)\n",
    "    y_pred = model.predict(X)\n",
    "    \n",
    "    # Calculate metrics\n",
    "    r2 = r2_score(y, y_pred)\n",
    "    adj_r2 = adjusted_r2_score(y, y_pred, n_samples, p)\n",
    "    results.append({'n_features': p, 'r2': r2, 'adj_r2': adj_r2})\n",
    "\n",
    "results_df = pd.DataFrame(results)\n",
    "print(\"Effect of adding features on R² and Adjusted R²:\")\n",
    "print(results_df.to_string(index=False))\n",
    "print()\n",
